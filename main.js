function validateForm(name, year, genre) {

    if (!name) {
        movieName.style.borderColor = "#ff4646";
        hasErrors = true;
    } else {
        movieName.style.borderColor = "#e4e4e4";
    }

    if (!year) {
        movieYear.style.borderColor = "#ff4646";
        hasErrors = true;
    } else if (year < 1888 || year > new Date().getFullYear()) {
        document.querySelector("#errorYear").textContent = "Invalid year";
        movieYear.style.borderColor = "#ff4646";
        hasErrors = true;
    } else {
        movieYear.style.borderColor = "#e4e4e4";
        document.querySelector("#errorYear").textContent = "";
    }

    if (!genre) {
        movieGenre.style.borderColor = "#ff4646";
        hasErrors = true;
    } else {
        movieGenre.style.borderColor = "#e4e4e4";
    }
}

